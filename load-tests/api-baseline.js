import http from "k6/http";
import { check, fail, sleep } from "k6";
import { Rate } from "k6/metrics";

const baseUrl = __ENV.BASE_URL || "http://127.0.0.1:8000";
const duration = __ENV.DURATION || "30s";
const readVus = Number(__ENV.READ_VUS || 10);
const writeRate = Number(__ENV.WRITE_RPS || 5);

const apiErrors = new Rate("api_errors");

export const options = {
  scenarios: {
    read_api: {
      executor: "constant-vus",
      exec: "readApi",
      vus: readVus,
      duration,
      gracefulStop: "5s",
      tags: { workload: "read" },
    },
    write_api: {
      executor: "constant-arrival-rate",
      exec: "writeApi",
      rate: writeRate,
      timeUnit: "1s",
      duration,
      preAllocatedVUs: Math.max(writeRate, 5),
      maxVUs: Math.max(writeRate * 4, 20),
      gracefulStop: "5s",
      tags: { workload: "write" },
    },
  },
  thresholds: {
    api_errors: ["rate<0.01"],
    checks: ["rate>0.99"],
    "http_req_duration{endpoint:logs_read}": ["p(95)<200"],
    "http_req_duration{endpoint:sync_read}": ["p(95)<200"],
    "http_req_duration{endpoint:logs_write}": ["p(95)<500"],
  },
};

function uuid() {
  return "xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx".replace(/[xy]/g, (char) => {
    const random = Math.floor(Math.random() * 16);
    const value = char === "x" ? random : (random & 0x3) | 0x8;
    return value.toString(16);
  });
}

function record(response, expectedStatus, name) {
  const success = check(response, {
    [`${name} status ${expectedStatus}`]: (result) => result.status === expectedStatus,
  });
  apiErrors.add(!success, { endpoint: name });
}

export function setup() {
  const response = http.post(
    `${baseUrl}/api/v1/auth/register`,
    JSON.stringify({
      email: `k6-${Date.now()}-${uuid()}@example.com`,
      password: "correct-horse-123",
    }),
    { headers: { "Content-Type": "application/json" }, tags: { endpoint: "setup_register" } }
  );
  if (response.status !== 201) fail(`setup registration failed: ${response.status}`);
  return { accessToken: response.json("access_token") };
}

function authHeaders(data) {
  return { Authorization: `Bearer ${data.accessToken}` };
}

export function readApi(data) {
  const responses = http.batch([
    {
      method: "GET",
      url: `${baseUrl}/api/v1/logs?date_from=2026-07-01&date_to=2026-07-31&limit=100`,
      params: { headers: authHeaders(data), tags: { endpoint: "logs_read" } },
    },
    {
      method: "GET",
      url: `${baseUrl}/api/v1/sync/changes?after=0&limit=100`,
      params: { headers: authHeaders(data), tags: { endpoint: "sync_read" } },
    },
  ]);
  record(responses[0], 200, "logs_read");
  record(responses[1], 200, "sync_read");
  sleep(0.2);
}

export function writeApi(data) {
  const response = http.post(
    `${baseUrl}/api/v1/logs`,
    JSON.stringify({
      client_id: uuid(),
      log_date: "2026-07-17",
      meal_type: "snack",
      custom_name: "k6 load-test meal",
      amount: 1,
      unit: "serving",
      nutrition: {
        kcal: 120,
        protein: 10,
        fat: 5,
        carbs: 20,
        sugar: 2,
        sodium: 300,
        caffeine: 0,
      },
      note: "generated by local k6 baseline",
    }),
    {
      headers: { ...authHeaders(data), "Content-Type": "application/json" },
      tags: { endpoint: "logs_write" },
    }
  );
  record(response, 201, "logs_write");
}
